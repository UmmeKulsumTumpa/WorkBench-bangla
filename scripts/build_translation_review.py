#!/usr/bin/env python3
"""Write docs/translation_review.md: side-by-side EN/BN for all 204 variants grouped by the 69 base
templates, each with one rendered example task, for the owner's native-speaker review. Stdlib only."""
import csv
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def cell(s):
    return s.replace("|", "\\|").replace("\r", "").replace("\n", "<br>")


def main():
    with open(os.path.join(ROOT, "data_bn", "templates_en.csv"), encoding="utf-8") as f:
        bases = list(csv.DictReader(f))
    with open(os.path.join(ROOT, "data_bn", "review_sheet.csv"), encoding="utf-8", newline="") as f:
        sheet = list(csv.DictReader(f))
    by_t = {}
    for r in sheet:
        by_t.setdefault(r["variant_id"].split(".")[0], []).append(r)
    out = [
        "# Translation review — all 204 EN/BN template variants",
        "",
        "Generated by `scripts/build_translation_review.py` from `data_bn/templates_bn.csv`. **Edit translations in "
        "`data_bn/templates_bn.csv` (column `template_bn`), not here.** `{slot}` is filled from the task "
        "(Bangla glossary value where one exists, see `data_bn/glossary.csv`); `{slot!en}` is always the raw English "
        "value (used inside quoted literals that reach a tool argument). The example row shows one real rendered task.",
        "",
    ]
    for b in bases:
        t = b["template_id"]
        out += [f"## {t} · {b['source_file']} · `{cell(b['base_template'])}`", "",
                "| variant | English | বাংলা |", "|---|---|---|"]
        for r in by_t[t]:
            out.append(f"| {r['variant_id']} | {cell(r['template_en'])} | {cell(r['template_bn'])} |")
        r0 = by_t[t][0]
        out.append(f"| *example* | *{cell(r0['example_task_en'])}* | *{cell(r0['example_task_bn'])}* |")
        out.append("")
    with open(os.path.join(ROOT, "docs", "translation_review.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"wrote docs/translation_review.md ({len(sheet)} variants, {len(bases)} templates)")


if __name__ == "__main__":
    main()
