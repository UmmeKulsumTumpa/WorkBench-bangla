#!/usr/bin/env python3
"""Write docs/conditions/translation_review.md: English vs Bangla side by side for every condition asset
(system-prompt lines and the 27 tool descriptions), for the native-speaker review.

    source env.sh && uv run --project WorkBench --frozen python scripts/build_condition_review.py
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WB = ROOT / "WorkBench"
sys.path.insert(0, str(WB))

from src.data_generation.data_generation_utils import HARDCODED_CURRENT_TIME  # noqa: E402
from src.evals.conditions import (  # noqa: E402
    CONDITIONS_DIR,
    act_without_confirmation_text,
    build_datetime_prefix,
    load_system_pack,
    load_tool_descriptions,
)
from src.tools.toolkits import all_tools  # noqa: E402

OUT = ROOT / "docs" / "conditions" / "translation_review.md"


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", "<br>")


def main() -> None:
    en, bn = load_system_pack("en"), load_system_pack("bn")
    tools_bn = load_tool_descriptions("bn")
    shas = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()[:12] for p in sorted((CONDITIONS_DIR / "bn").glob("*.json"))}
    lines = [
        "# Condition assets: English vs Bangla (review sheet)",
        "",
        "Generated by `scripts/build_condition_review.py`; do not edit by hand. Edit the JSON files in "
        "`WorkBench/data/conditions/bn/`, then regenerate. Asset hashes: "
        + ", ".join(f"`{k}` {v}" for k, v in shas.items())
        + ".",
        "",
        "Reviewer checklist: meaning identical; তুমি register as in the task templates; identifiers, quoted strings, "
        "formats and examples unchanged; ASCII digits only; status/field values (`Lead`, `Won`, `Backlog`) in English.",
        "",
        "## 1. System prompt (c2, c3)",
        "",
        "| piece | English | Bangla |",
        "|---|---|---|",
        f"| date line (as sent, 2023-11-30) | {cell(build_datetime_prefix(HARDCODED_CURRENT_TIME, 'en'))} "
        f"| {cell(build_datetime_prefix(HARDCODED_CURRENT_TIME, 'bn'))} |",
        f"| act without confirmation | {cell(act_without_confirmation_text('en'))} | {cell(act_without_confirmation_text('bn'))} |",
        f"| output-language line (template) | {cell(en['output_language_instruction'])} | {cell(bn['output_language_instruction'])} |",
        "| weekdays | " + ", ".join(en["weekdays"]) + " | " + ", ".join(bn["weekdays"].values()) + " |",
        "",
        "c4 and c5 use the **English** output-language line (their system prompt is English): "
        f"`{en['output_language_instruction'].format(language='English')}` / "
        f"`{en['output_language_instruction'].format(language='Bangla')}`.",
        "",
        "## 2. Tool descriptions (c3)",
        "",
    ]
    for t in all_tools:
        lines += [f"### `{t.name}`", "", "| English | Bangla |", "|---|---|",
                  f"| {cell(t.description.strip())} | {cell(tools_bn[t.name].strip())} |", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(all_tools)} tools)")


if __name__ == "__main__":
    main()
